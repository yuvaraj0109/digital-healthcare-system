import React from 'react';
import { X, Download, FileText, ExternalLink, ShieldCheck } from 'lucide-react';

const ReportViewerModal = ({ isOpen, onClose, reportUrl, reportName, bookingId }) => {
  if (!isOpen || !reportUrl) return null;

  const fullReportUrl = reportUrl.startsWith('http') ? reportUrl : `${window.location.origin}${reportUrl}`;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-fade-in">
      <div className="bg-white rounded-2xl shadow-2xl max-w-4xl w-full overflow-hidden flex flex-col max-h-[90vh] border border-slate-200">
        {/* Header */}
        <div className="bg-gradient-to-r from-teal-700 to-teal-800 text-white p-4 px-6 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-white/10 flex items-center justify-center">
              <FileText className="w-5 h-5 text-teal-200" />
            </div>
            <div>
              <h3 className="font-semibold text-lg leading-tight">Diagnostic Test Report</h3>
              <p className="text-xs text-teal-100 flex items-center gap-1">
                <ShieldCheck className="w-3.5 h-3.5 text-teal-300" /> Ref ID: {bookingId}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <a
              href={fullReportUrl}
              download={reportName || `Report_${bookingId}.pdf`}
              className="px-3.5 py-1.5 bg-white/10 hover:bg-white/20 text-white rounded-lg text-xs font-medium flex items-center gap-1.5 transition"
            >
              <Download className="w-4 h-4" /> Download PDF
            </a>
            <button
              onClick={onClose}
              className="p-1.5 rounded-lg hover:bg-white/10 text-white/80 hover:text-white transition"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Content Body */}
        <div className="p-4 bg-slate-100 flex-1 flex flex-col items-center justify-center min-h-[400px]">
          <iframe
            src={fullReportUrl}
            title={`Report ${bookingId}`}
            className="w-full h-[550px] rounded-xl border border-slate-200 shadow-inner bg-white"
          />
        </div>

        {/* Footer */}
        <div className="p-4 bg-white border-t border-slate-200 flex items-center justify-between text-xs text-slate-500">
          <span>Official Medical Report Document generated by AuraHealth Lab Information System</span>
          <a
            href={fullReportUrl}
            target="_blank"
            rel="noreferrer"
            className="text-teal-600 hover:text-teal-700 font-medium flex items-center gap-1"
          >
            Open in new tab <ExternalLink className="w-3.5 h-3.5" />
          </a>
        </div>
      </div>
    </div>
  );
};

export default ReportViewerModal;
